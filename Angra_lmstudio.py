def write_plugin_files(app: App, stamp: str) -> List[str]:
    """Write Angra-owned plugin files. Refuses to touch a directory Angra does not own."""
    d = app.plugin_dir
    if d.exists() and not (d / PLUGIN_MARKER).is_file() and any(d.iterdir()):
        raise UserError("Refusing to overwrite a folder Angra does not own:", ["  " + str(d)])
    d.mkdir(parents=True, exist_ok=True)
    changed: List[str] = []
    allfiles = dict(plugin_files(app.home))
    allfiles[PLUGIN_MARKER] = "angra-bridge %s\n" % ANGRA_VERSION
    for rel, content in allfiles.items():
        p = d / rel
        data = content.encode("utf-8")
        if p.is_file() and p.read_bytes() == data:
            continue
        if p.exists():
            backup_file(app.home, p, stamp)
        atomic_write(p, data)
        changed.append(rel)
    return changed


def write_launcher(app: App, stamp: str) -> bool:
    data = encode_launcher(launcher_text(sys.executable, app.script_copy))
    if app.launcher.is_file() and app.launcher.read_bytes() == data:
        return False
    if app.launcher.exists():
        backup_file(app.home, app.launcher, stamp)
    atomic_write(app.launcher, data)
    return True


def install_self(app: App, stamp: str) -> bool:
    src = Path(os.path.abspath(__file__))
    dst = app.script_copy
    with contextlib.suppress(OSError):
        if dst.exists() and os.path.samefile(str(src), str(dst)):
            return False
    data = src.read_bytes()
    if dst.is_file() and dst.read_bytes() == data:
        return False
    if dst.exists():
        backup_file(app.home, dst, stamp)
    atomic_write(dst, data)
    return True


def register_plugin(app: App, lms: str) -> Tuple[bool, str]:
    """Official mechanism: `lms dev --install` from the plugin directory."""
    cwd = str(app.plugin_dir)
    for cmd in ([lms, "dev", "--install", "-y"], [lms, "dev", "--install"]):
        with Spinner("Registering the plugin with LM Studio"):
            rc, out, err = run(cmd, timeout=240, cwd=cwd)
        text = (out + err).strip()
        if rc == 0:
            log.info("plugin registered via: %s", " ".join(cmd[1:]))
            return True, "registered via `lms %s`" % " ".join(cmd[1:])
        if rc == 124:
            return False, "`lms dev --install` timed out (LM Studio may be waiting). Try it manually in the plugin folder."
        low = text.lower()
        if "unknown" in low or "unrecognized" in low or "invalid option" in low:
            continue
        return False, "`lms %s` failed: %s" % (" ".join(cmd[1:]), text[:300])
    return False, "`lms dev --install` rejected the options in this LM Studio version"


def cmd_install(app: App, repair: bool = False) -> int:
    if os.name != "nt":
        raise UserError("Angra install supports Windows only.",
                        ["Read-only commands (models, loaded, doctor, self-test) still run elsewhere."])
    if sys.version_info < (3, 8):
        raise UserError("Python 3.8 or newer is required.")
    banner()
    title = "REPAIR" if repair else "INSTALL"
    section(title.capitalize())
    step("ok", "Windows / Python %s" % sys.version.split()[0])
    stamp = time.strftime("%Y%m%d-%H%M%S")
    setup_logging(app.home)
    app.home.mkdir(parents=True, exist_ok=True)
    for sub in ("bin", "logs", "backups", "plugin"):
        (app.home / sub).mkdir(parents=True, exist_ok=True)
    st = app.state()
    inst = st["installation"]
    partial = False

    lms = app.lms()
    app_path = find_lmstudio_app()
    step("ok" if app_path else "??", "LM Studio %s" % (app_path or "application not located"))
    if not lms:
        raise UserError("The `lms` CLI was not found.", [
            "Start LM Studio once, then run `lms bootstrap` (or enable the CLI in LM Studio),",
            "and run `py Angra.py install` again."])
    rc, _, err = run([lms, "--help"], timeout=20)
    if rc != 0:
        raise UserError("`lms --help` failed.", [err.strip()[:200]])
    step("ok", "lms CLI %s" % lms)
    inst["lms_path"] = lms

    cfgp = app.home / "config.json"
    if not cfgp.is_file():
        atomic_write_text(cfgp, json.dumps(DEFAULT_CONFIG, indent=2) + "\n")
        step("ok", "config created")
    if install_self(app, stamp):
        step("ok", "Angra.py copied to %s" % app.script_copy)
    changed = write_plugin_files(app, stamp)
    step("ok", "plugin project %s (%d file(s) written)" % (app.plugin_dir, len(changed)))
    inst.update({"home": str(app.home), "plugin_dir": str(app.plugin_dir)})

    capable, msg = lms_dev_install_capable(lms)
    step("ok" if capable else "!!", "plugin support: %s" % msg)
    if capable and (changed or not inst.get("plugin_registered") or not repair):
        ok, detail = register_plugin(app, lms)
        inst["plugin_registered"] = ok
        step("ok" if ok else "!!", detail)
        partial |= not ok
    elif not capable:
        partial = True
        print("      Fallback: run `lms dev` inside the plugin folder to load it in development mode.")

    if write_launcher(app, stamp):
        step("ok", "launcher %s" % app.launcher)
    inst["launcher"] = str(app.launcher)
    inst["path_entry"] = str(app.bin_dir)
    try:
        if not user_path_has(str(app.bin_dir)):
            user_path_add(str(app.bin_dir))
            inst["path_added"] = True
            step("ok", "added launcher directory to your user PATH")
        else:
            step("ok", "launcher directory already on user PATH")
    except OSError as e:
        partial = True
        step("!!", "could not update user PATH: %s" % e)

    if not inst.get("installed_at"):
        inst["installed_at"] = now_iso()
    inst["installed"] = True
    app.store.save(st)
    log.info("%s finished (partial=%s)", title.lower(), partial)

    cmdline = 'cmd.exe /d /s /c ""%s" version"' % app.launcher
    try:
        p = subprocess.run(cmdline, capture_output=True, timeout=30, shell=False, stdin=subprocess.DEVNULL)
        vok = p.returncode == 0 and ANGRA_VERSION.encode() in p.stdout
    except (OSError, subprocess.TimeoutExpired):
        vok = False
    step("ok" if vok else "!!", "launcher check: `angra version`")
    partial |= not vok
    print()
    rep = run_doctor(app)
    rep.print()
    print()
    if partial or rep.count("FAIL"):
        print(paint("Installation finished with issues (see above).", "yellow"))
    else:
        print(paint("Installation complete.", "green"))
    print("Open a NEW Command Prompt window (PATH changes apply to new windows), then run:  angra")
    return 2 if (partial or rep.count("FAIL")) else 0


def cmd_repair(app: App) -> int:
    if not (app.home / "state.json").exists() and not app.plugin_dir.exists():
        raise UserError("Angra is not installed.", ["Run: py Angra.py install"])
    return cmd_install(app, repair=True)


def confirm(prompt: str) -> bool:
    if not sys.stdin.isatty():
        return False
    try:
        return input(prompt).strip().lower() == "yes"
    except (EOFError, KeyboardInterrupt):
        return False


def _safe_rmtree(target: Path, must_be_inside: Path) -> bool:
    t, root = target.resolve(), must_be_inside.resolve()
    if root not in t.parents:
        return False
    shutil.rmtree(str(t), ignore_errors=True)
    return True


def cmd_uninstall(app: App) -> int:
    st = app.state()
    section("Uninstall")
    print("This will remove ONLY Angra-owned items:")
    print("  - the Angra plugin (registered copy + generated project)")
    print("  - the angra.cmd launcher and the user PATH entry Angra added")
    print("  - Angra state, config, logs and backups in %s" % app.home)
    print("LM Studio, your models and other plugins are never touched.")
    if not confirm("Type YES to continue: "):
        print("Cancelled. Nothing was changed.")
        return 1
    setup_logging(app.home)
    log.info("uninstall confirmed")
    lms = app.lms()

    # Plugin: no documented uninstall command was verified, so only remove the exact
    # registered copy that matches our owner/name manifest, inside the plugins root.
    removed = 0
    for d in find_installed_plugin_dirs():
        if _safe_rmtree(d, plugins_root()):
            removed += 1
    step("ok", "registered plugin copies removed: %d" % removed)
    if lms is None:
        step("--", "lms not found; if the plugin still shows in LM Studio, remove it there.")

    marker_ok = (app.plugin_dir / PLUGIN_MARKER).is_file()
    if app.plugin_dir.exists():
        if marker_ok and _safe_rmtree(app.plugin_dir, app.home):
            step("ok", "generated plugin project removed")
        else:
            step("!!", "%s has no Angra marker; left untouched" % app.plugin_dir)
    with contextlib.suppress(OSError):
        (app.home / "plugin").rmdir()

    if app.launcher.is_file():
        app.launcher.unlink()
        step("ok", "launcher removed")
    with contextlib.suppress(OSError):
        app.bin_dir.rmdir()

    inst = st["installation"]
    if winreg is not None and inst.get("path_added") and inst.get("path_entry"):
        try:
            if user_path_remove(str(inst["path_entry"])):
                step("ok", "removed Angra's user PATH entry")
        except OSError as e:
            step("!!", "could not edit user PATH: %s" % e)

    logging.shutdown()
    for h in list(log.handlers):
        log.removeHandler(h)
    for rel in ("state.json", "config.json", "Angra.py"):
        with contextlib.suppress(OSError):
            (app.home / rel).unlink()
    for name in list(os.listdir(str(app.home))) if app.home.is_dir() else []:
        if name.startswith("state.json.corrupt-") or name.startswith("state.json.") and name.endswith(".tmp"):
            with contextlib.suppress(OSError):
                (app.home / name).unlink()
    for sub in ("logs", "backups"):
        _safe_rmtree(app.home / sub, app.home) if (app.home / sub).exists() else None
    with contextlib.suppress(OSError):
        app.home.rmdir()
    step("ok", "Angra files removed" + ("" if not app.home.exists() else " (folder kept: contains other files)"))
    print("Uninstall complete. Open a new Command Prompt window for PATH to refresh.")
    return 0


