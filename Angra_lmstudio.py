def link_state(st: dict, snap: Snapshot, primary: str, helper: str) -> str:
    by_key = {m.key: m for m in snap.models}
    h, p = by_key.get(helper), by_key.get(primary)
    if not (h and h.loaded) or not (p and p.loaded):
        return "PAUSED"
    return "CONNECTED" if perm_effective(st, helper)[1] else "LINKED"


def model_tags(st: dict, snap: Snapshot, m: Model) -> str:
    tags = []
    if st["primary"] == m.key:
        tags.append(tag("Primary", "clay"))
    helper_of = [p for p, hs in st["links"].items() if m.key in hs]
    if helper_of:
        tags.append(tag("Helper", "blue"))
    if perm_effective(st, m.key)[1]:
        tags.append(tag("Authorized", "sand"))
    for p in helper_of:
        s = link_state(st, snap, p, m.key)
        if s == "CONNECTED":
            tags.append(tag("Connected", "green"))
            break
        if s == "PAUSED":
            tags.append(tag("Paused", "yellow"))
            break
    return "  ".join(tags)


