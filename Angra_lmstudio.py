@dataclass
class Model:
    key: str
    name: str
    path: str = ""
    arch: str = ""
    params: str = ""
    size: int = 0
    loaded: bool = False
    identifiers: List[str] = field(default_factory=list)

    def aliases(self) -> set:
        a = {self.key.lower(), self.name.lower()} | {i.lower() for i in self.identifiers}
        if self.path:
            a.add(Path(self.path.replace("\\", "/")).stem.lower())
        return {x for x in a if x}


@dataclass
class Snapshot:
    models: List[Model]
    ls_ok: bool
    ps_ok: bool
    errors: List[str]


def _first(d: dict, keys: Tuple[str, ...]):
    for k in keys:
        v = d.get(k)
        if v not in (None, ""):
            return v
    return None


def _entries(obj) -> List[dict]:
    if isinstance(obj, dict):
        for k in ("models", "data", "items", "result"):
            if isinstance(obj.get(k), list):
                obj = obj[k]
                break
        else:
            return []
    return [e for e in obj if isinstance(e, dict)] if isinstance(obj, list) else []


def _is_embedding(e: dict) -> bool:
    return str(e.get("type", "")).lower().startswith("embed")


def discover(lms: Optional[str]) -> Snapshot:
    with Spinner("Reading LM Studio"):
        return _discover_impl(lms)


def _discover_impl(lms: Optional[str]) -> Snapshot:
    if not lms:
        return Snapshot([], False, False, ["lms CLI not found"])
    errors: List[str] = []
    models: Dict[str, Model] = {}
    by_path: Dict[str, str] = {}
    ls_ok = ps_ok = False

    rc, out, err = run([lms, "ls", "--json"], timeout=45)
    if rc == 0:
        try:
            for e in _entries(parse_json_output(out)):
                if _is_embedding(e):
                    continue
                path = str(_first(e, ("path",)) or "")
                key = str(_first(e, ("modelKey", "model_key", "key", "id")) or Path(path.replace("\\", "/")).stem)
                if not key:
                    continue
                name = str(_first(e, ("displayName", "display_name", "name")) or key)
                size = _first(e, ("sizeBytes", "size_bytes", "size")) or 0
                models[key.lower()] = Model(
                    key=key, name=name, path=path,
                    arch=str(_first(e, ("architecture", "arch")) or ""),
                    params=str(_first(e, ("paramsString", "params")) or ""),
                    size=size if isinstance(size, int) else 0)
                if path:
                    by_path[path.lower()] = key.lower()
            ls_ok = True
        except ValueError as ex:
            errors.append("lms ls --json: unreadable output (%s)" % ex)
    else:
        errors.append("lms ls --json failed: %s" % (err.strip() or out.strip() or "rc=%d" % rc)[:200])

    rc, out, err = run([lms, "ps", "--json"], timeout=30)
    if rc == 0:
        try:
            for e in _entries(parse_json_output(out)):
                if _is_embedding(e):
                    continue
                path = str(_first(e, ("path",)) or "")
                ident = str(_first(e, ("identifier", "id")) or "")
                key = str(_first(e, ("modelKey", "model_key", "key")) or ident or path)
                k = key.lower()
                if k not in models and path and path.lower() in by_path:
                    k = by_path[path.lower()]
                if k not in models:
                    name = str(_first(e, ("displayName", "display_name", "name")) or key)
                    models[k] = Model(key=key, name=name, path=path)
                m = models[k]
                m.loaded = True
                if ident and ident not in m.identifiers:
                    m.identifiers.append(ident)
            ps_ok = True
        except ValueError as ex:
            errors.append("lms ps --json: unreadable output (%s)" % ex)
    else:
        errors.append("lms ps --json failed: %s" % (err.strip() or out.strip() or "rc=%d" % rc)[:200])

    ordered = sorted(models.values(), key=lambda m: (not m.loaded, m.name.lower()))
    return Snapshot(ordered, ls_ok, ps_ok, errors)


def validate_name(name: str) -> str:
    n = (name or "").strip()
    if not n or len(n) > 200:
        raise UserError("Invalid model name.", ["Model names must be 1-200 characters."])
    if any(ord(c) < 32 for c in n) or ".." in n.replace("\\", "/").split("/") or n[0] in "/\\" or ":" in n[:2]:
        raise UserError("Invalid model name.", ["Path-like or control characters are not allowed."])
    return n


def find_lmstudio_app() -> Optional[str]:
    cands: List[Path] = []
    for env in ("LOCALAPPDATA", "ProgramFiles", "ProgramFiles(x86)"):
        v = os.environ.get(env)
        if v:
            cands.append(Path(v) / "Programs" / "LM Studio" / "LM Studio.exe")
            cands.append(Path(v) / "LM Studio" / "LM Studio.exe")
    for c in cands:
        if c.is_file():
            return str(c)
    if winreg is not None:
        for hive in (winreg.HKEY_CURRENT_USER, winreg.HKEY_LOCAL_MACHINE):
            with contextlib.suppress(OSError):
                with winreg.OpenKey(hive, r"Software\Microsoft\Windows\CurrentVersion\Uninstall") as root:
                    i = 0
                    while True:
                        try:
                            sub = winreg.EnumKey(root, i)
                        except OSError:
                            break
                        i += 1
                        with contextlib.suppress(OSError):
                            with winreg.OpenKey(root, sub) as k:
                                disp = winreg.QueryValueEx(k, "DisplayName")[0]
                                if str(disp).startswith("LM Studio"):
                                    loc = winreg.QueryValueEx(k, "InstallLocation")[0]
                                    if loc:
                                        return str(loc)
    return None


def find_lms(cfg: dict) -> Optional[str]:
    if cfg.get("lms_path") and Path(str(cfg["lms_path"])).is_file():
        return str(cfg["lms_path"])
    w = shutil.which("lms")
    if w:
        return w
    for name in ("lms.exe", "lms"):  # documented default location of the lms CLI
        c = Path.home() / ".lmstudio" / "bin" / name
        if c.is_file():
            return str(c)
    return None


def plugins_root() -> Path:
    return Path.home() / ".lmstudio" / "extensions" / "plugins"


def find_installed_plugin_dirs() -> List[Path]:
    """Read-only scan for a registered copy of our plugin (layout not assumed)."""
    root = plugins_root()
    found: List[Path] = []
    if not root.is_dir():
        return found
    base_depth = len(root.parts)
    for dp, dns, fns in os.walk(str(root)):
        if len(Path(dp).parts) - base_depth > 3:
            dns[:] = []
            continue
        dns[:] = [d for d in dns if d not in ("node_modules", "dist", ".git")]
        if "manifest.json" in fns:
            with contextlib.suppress(OSError, ValueError):
                m = json.loads((Path(dp) / "manifest.json").read_text(encoding="utf-8"))
                if m.get("name") == PLUGIN_NAME and m.get("owner") == PLUGIN_OWNER:
                    found.append(Path(dp))
    return found


