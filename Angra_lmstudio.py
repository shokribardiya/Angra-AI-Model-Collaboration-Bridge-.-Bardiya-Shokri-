    sym = {"PASS": (gl("tick"), "green"), "WARN": (gl("warn"), "yellow"), "FAIL": (gl("cross"), "red"), "SKIP": (gl("dash"), "grey")}[level]
    return paint(sym[0], sym[1], "bold")


