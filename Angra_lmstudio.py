def default_state() -> dict:
    return {
        "version": ANGRA_VERSION, "schema": STATE_SCHEMA, "primary": None, "helpers": [],
        "links": {}, "permissions": {}, "safety": dict(DEFAULT_SAFETY),
        "installation": {
            "installed": False, "installed_at": None, "home": None, "plugin_dir": None,
            "plugin_registered": False, "launcher": None, "path_entry": None,
            "path_added": False, "lms_path": None,
        },
        "created_at": now_iso(), "updated_at": now_iso(),
    }


def sanitize_safety(s: object) -> dict:
    out = dict(DEFAULT_SAFETY)
    if isinstance(s, dict):
        def clamp(k: str, lo: int, hi: int) -> None:
            v = s.get(k)  # type: ignore[union-attr]
            if isinstance(v, int) and not isinstance(v, bool):
                out[k] = max(lo, min(hi, v))
        clamp("max_helper_context", 256, 32768)
        clamp("max_helper_output", 16, 4096)
        clamp("timeout_seconds", 5, 600)
        clamp("cooldown_seconds", 0, 600)
    # v1 hard invariants: cannot be relaxed through the state file.
    out["max_active_helpers"] = 1
    out["parallel_helpers"] = False
    out["max_helper_calls_per_response"] = 1
    out["recursive_delegation"] = False
    return out


def migrate_state(raw: object) -> dict:
    st = default_state()
    if not isinstance(raw, dict):
        return st
    if isinstance(raw.get("primary"), str):
        st["primary"] = raw["primary"]
    if isinstance(raw.get("links"), dict):
        st["links"] = {str(k): [str(x) for x in v] for k, v in raw["links"].items() if isinstance(v, list) and v}
    if isinstance(raw.get("permissions"), dict):
        st["permissions"] = {str(k): dict(v) for k, v in raw["permissions"].items() if isinstance(v, dict)}
    st["safety"] = sanitize_safety(raw.get("safety"))
    st["helpers"] = sorted({h for hs in st["links"].values() for h in hs})
    if isinstance(raw.get("installation"), dict):
        st["installation"].update(raw["installation"])
    for k in ("created_at", "updated_at"):
        if isinstance(raw.get(k), str):
            st[k] = raw[k]
    st["schema"] = STATE_SCHEMA
    st["version"] = ANGRA_VERSION
    return st


class Store:
    def __init__(self, path: Path):
        self.path = path

    def load(self) -> dict:
        try:
            raw = json.loads(self.path.read_text(encoding="utf-8"))
        except FileNotFoundError:
            return default_state()
        except (OSError, ValueError):
            stamp = time.strftime("%Y%m%d-%H%M%S")
            with contextlib.suppress(OSError):
                shutil.copy2(str(self.path), str(self.path) + ".corrupt-" + stamp)
            log.warning("state file unreadable; reset (copy kept)")
            return default_state()
        return migrate_state(raw)

    def save(self, st: dict) -> None:
        st["helpers"] = sorted({h for hs in st["links"].values() for h in hs})
        st["links"] = {k: v for k, v in st["links"].items() if v}
        st["updated_at"] = now_iso()
        atomic_write_text(self.path, json.dumps(st, indent=2, ensure_ascii=False) + "\n")


