def dispatch(app: App, argv: List[str]) -> int:
    cmd, args = argv[0].lower(), argv[1:]
    table: Dict[str, Callable[[], int]] = {
        "status": lambda: cmd_status(app),
        "models": lambda: (print_models(app), 0)[1],
        "loaded": lambda: (print_models(app, only_loaded=True), 0)[1],
        "primary": lambda: cmd_primary(app, args),
        "link": lambda: cmd_link(app, args),
        "unlink": lambda: cmd_unlink(app, args),
        "connect": lambda: cmd_connect(app, args),
        "disconnect": lambda: cmd_disconnect(app, args),
        "allow": lambda: cmd_allow(app, args),
        "deny": lambda: cmd_deny(app, args),
        "permissions": lambda: (print_permissions(app), 0)[1],
        "links": lambda: (print_links(app), 0)[1],
        "doctor": lambda: (lambda r: (r.print(), 1 if r.count("FAIL") else 0)[1])(run_doctor(app)),
        "self-test": lambda: (lambda r: (r.print(), 1 if r.count("FAIL") else 0)[1])(run_self_test(app)),
        "install": lambda: cmd_install(app),
        "repair": lambda: cmd_repair(app),
        "uninstall": lambda: cmd_uninstall(app),
        "version": cmd_version,
        "help": lambda: (print_help(HELP), 0)[1],
    }
    if cmd in ("exit", "quit"):
        return 0
    fn = table.get(cmd)
    if fn is None:
        raise UserError("Unknown command '%s'." % argv[0], ["Run: angra help"])
    log.info("command: %s", cmd)
    return fn()


def shell(app: App) -> int:
    spark_intro()
    prompt = prompt_str("angra")
    while True:
        try:
            line = input(prompt)
        except (EOFError, KeyboardInterrupt):
            print()
            return 0
        line = line.strip()
        if not line:
            continue
        if line.lower().startswith("angra "):
            line = line[6:]
        try:
            parts = shlex.split(line)
        except ValueError as e:
            print("Parse error: %s" % e)
            continue
        if parts and parts[0].lower() in ("exit", "quit"):
            return 0
        try:
            dispatch(app, parts)
        except UserError as e:
            print_error(e)
        print()


def main(argv: List[str]) -> int:
    force_plain = "--no-color" in argv
    force_ascii = "--ascii" in argv
    no_anim = "--no-anim" in argv
    argv = [a for a in argv if a not in ("--no-color", "--ascii", "--no-anim")]
    app = App()
    setup_terminal(app.cfg, force_plain, force_ascii, no_anim)
    if app.home.is_dir():
        setup_logging(app.home)
    try:
        if not argv:
            banner()
            print_dashboard(app)
            if sys.stdin.isatty():
                print("  " + paint("Type `help` for commands, `exit` to leave.", "dim") + "\n")
                return shell(app)
            return 0
        if argv[0] in ("-h", "--help"):
            argv = ["help"]
        return dispatch(app, argv)
    except UserError as e:
        print_error(e)
        return 1
    except KeyboardInterrupt:
        print("\nInterrupted.")
        return 130
    except BrokenPipeError:
        return 0
    except OSError as e:
        print(paint("ERROR", "red", "bold"))
        print("File or system problem: %s" % e)
        log.error("OSError: %s", e)
        return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
