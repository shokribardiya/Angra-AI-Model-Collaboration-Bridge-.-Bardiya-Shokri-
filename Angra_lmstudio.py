def perm_effective(st: dict, key: str, now: Optional[float] = None) -> Tuple[str, bool]:
    now = time.time() if now is None else now
    p = st["permissions"].get(key) or {}
    mode = str(p.get("mode", "off")).lower()
    if mode in ("once", "enabled"):
        return mode, True
    if mode == "session":
        exp = p.get("expires_at")
        if isinstance(exp, (int, float)) and now < exp:
            return "session", True
        return "session-expired", False
    return "off", False


def graph_add_error(st: dict, primary: str, helper: str) -> Optional[str]:
    """Return why the edge primary->helper is forbidden, or None if allowed."""
    if primary == helper:
        return "A model cannot be its own helper."
    links = st["links"]
    if links.get(helper):
        return "'%s' is already a primary for other helpers. Helper chains are disabled." % helper
    if any(primary in hs for hs in links.values()):
        return "'%s' is already a helper of another primary. Helper chains are disabled." % primary
    # explicit cycle check (defence in depth)
    seen, stack = set(), [helper]
    while stack:
        n = stack.pop()
        if n == primary:
            return "This link would create a cycle."
        if n in seen:
            continue
        seen.add(n)
        stack.extend(links.get(n, []))
    return None


