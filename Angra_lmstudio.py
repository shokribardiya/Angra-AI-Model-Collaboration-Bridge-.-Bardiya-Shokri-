def run(cmd: List[str], timeout: int = 30, cwd: Optional[str] = None) -> Tuple[int, str, str]:
    """Run an argument-array command (never shell=True), bounded and timed out."""
    try:
        p = subprocess.run(cmd, capture_output=True, timeout=timeout, cwd=cwd,
                           shell=False, stdin=subprocess.DEVNULL)
    except FileNotFoundError:
        return 127, "", "executable not found"
    except subprocess.TimeoutExpired:
        return 124, "", "timed out after %ss" % timeout
    except OSError as e:
        return 126, "", str(e)
    return (p.returncode, p.stdout[:MAX_OUT].decode("utf-8", "replace"),
            p.stderr[:MAX_OUT].decode("utf-8", "replace"))


def parse_json_output(text: str):
    dec = json.JSONDecoder()
    tries = 0
    for i, ch in enumerate(text):
        if ch in "[{":
            tries += 1
            if tries > 50:
                break
            try:
                obj, _ = dec.raw_decode(text[i:])
                return obj
            except ValueError:
                continue
    raise ValueError("no JSON found in output")


